from typing import TYPE_CHECKING

import rich_click as click
import yaml
from rich.console import Console
from rich.table import Table
from rich.tree import Tree

if TYPE_CHECKING:
    import h5py

from metacooler.cli.main import MetaCoolURI, cli

# Exact order for JSON output as requested
_INFO_KEY_ORDER = [
    "bin-size",
    "bin-type",
    "creation-date",
    "format",
    "format-url",
    "format-version",
    "metacooler-format-version",
    "generated-by",
    "genome-assembly",
    "nbins",
    "ncontigs",
    "ngenomes",
    "nnz",
    "storage-mode",
    "sum",
    "ordering",
]


@cli.command(name="info", help="Display metadata and statistics.")
@click.argument("metacool_path", type=MetaCoolURI())
@click.option(
    "--table",
    "table_out",
    is_flag=True,
    help="Output as a rich table instead of JSON.",
)
@click.option(
    "-v",
    "--verbose",
    is_flag=True,
    help="Increase verbosity (debug logging).",
)
def cmd_info(metacool_path: str, table_out: bool, verbose: bool) -> None:
    """Display metadata and statistics for a metacool file."""
    import cooler
    import h5py
    from cooler.fileops import is_cooler, is_multires_file

    from metacooler.api import MetaCooler
    from metacooler.cli.logging_utils import setup_logging
    from metacooler.schema import is_metacooler, is_mmetacooler, list_metacoolers
    from metacooler.uri import parse_uri

    setup_logging(verbose, command_name="metacooler info")

    raw = metacool_path
    file_path, group_path = parse_uri(raw)

    # Check if this is an mmetacool without a group path
    if is_mmetacooler(file_path) and "::" not in raw:
        entries = list_metacoolers(file_path)
        entry_uris = [f"{file_path}::{e}" for e in entries]
        raise click.ClickException(
            f"This is an mmetacool file with {len(entries)} entries. "
            f"Specify an entry with URI syntax:\n"
            + "\n".join(f"  metacooler info {u}" for u in entry_uris)
        )

    # Check if this is an mcool without a resolution path
    if is_multires_file(str(file_path)) and group_path == "/":
        with h5py.File(file_path, "r") as f:
            resolutions = list(f["resolutions"])
        raise click.ClickException(
            f"This is a multi-resolution cooler with resolutions: {resolutions}. "
            f"Specify a resolution with URI syntax:\n"
            + "\n".join(
                f"  metacooler info {file_path}::resolutions/{r}" for r in resolutions
            )
        )

    # Plain cooler (or mcool with resolution URI): fall back to cooler.Cooler
    if not is_metacooler(file_path) and not ("::" in raw and is_mmetacooler(file_path)):
        cooler_uri = str(file_path) if group_path == "/" else raw
        if not is_cooler(cooler_uri):
            raise click.ClickException(
                f"Not a recognised metacooler or cooler file: {file_path}"
            )
        clr = cooler.Cooler(cooler_uri)
        click.echo(json.dumps(dict(clr.info), indent=2, default=str))
        return

    mc = MetaCooler(raw)
    info = mc.info

    # Build ordered dict
    ordered_info = {}
    for key in _INFO_KEY_ORDER:
        if key in info:
            ordered_info[key] = info[key]

    if table_out:
        table = Table(
            title=f"MetaCooler Info: {Path(metacool_path.split('::')[0]).name}"
        )
        table.add_column("Property", style="cyan")
        table.add_column("Value", style="magenta")

        table.add_row("Format", str(ordered_info.get("format", "N/A")))
        table.add_row("Format URL", str(ordered_info.get("format-url", "N/A")))
        table.add_row("Format version", str(ordered_info.get("format-version", "N/A")))
        table.add_row("Generated by", str(ordered_info.get("generated-by", "N/A")))
        table.add_row("Assembly", str(ordered_info.get("genome-assembly", "N/A")))
        table.add_row("Ordering", str(ordered_info.get("ordering", "N/A")))
        table.add_row("Genomes", str(ordered_info.get("ngenomes", "N/A")))
        table.add_row("Contigs", str(ordered_info.get("ncontigs", "N/A")))
        table.add_row("Bins", str(ordered_info.get("nbins", "N/A")))
        table.add_row("Pixels (NNZ)", str(ordered_info.get("nnz", "N/A")))
        table.add_row("Sum", str(ordered_info.get("sum", "N/A")))
        table.add_row("Bin size", str(ordered_info.get("bin-size", "N/A")))
        table.add_row("Bin type", str(ordered_info.get("bin-type", "N/A")))

        console = Console()
        console.print(table)
        return

    click.echo(json.dumps(ordered_info, indent=2, default=str))


@cli.command(name="tree", help="Display the data hierarchy.")
@click.argument("metacool_path", type=MetaCoolURI())
@click.option(
    "-v",
    "--verbose",
    is_flag=True,
    help="Increase verbosity (debug logging).",
)
def cmd_tree(metacool_path: str, verbose: bool) -> None:
    """Display the HDF5 hierarchy as a tree."""
    import h5py

    from metacooler.cli.logging_utils import setup_logging
    from metacooler.schema import is_metacooler, is_mmetacooler
    from metacooler.uri import parse_uri

    setup_logging(verbose, command_name="metacooler tree")
    console = Console()

    file_path, group_path = parse_uri(metacool_path)

    def _build_tree(name: str, obj, parent: Tree) -> None:
        if isinstance(obj, h5py.Group):
            node = parent.add(f"[bold]{name}/[/bold]")
            for key, child in obj.items():
                _build_tree(key, child, node)
        elif isinstance(obj, h5py.Dataset):
            shape = " × ".join(str(s) for s in obj.shape)
            dtype = str(obj.dtype)
            parent.add(f"{name} [dim]({shape}, {dtype})[/dim]")

    with h5py.File(file_path, "r") as f:
        tree = Tree(f"[bold]{file_path.name}[/bold]")

        if group_path != "/":
            # URI points to a specific entry — show its tree
            entry = f[group_path]
            for key in ("genomes", "contigs", "bins", "pixels", "indexes"):
                if key in entry:
                    _build_tree(key, entry[key], tree)
        elif is_mmetacooler(file_path):
            # Show top-level entries, then tree of each entry
            if "entries" in f:
                entries_node = tree.add("[bold]entries/[/bold]")
                for entry_name in f["entries"]:
                    entry_node = entries_node.add(f"[bold]{entry_name}/[/bold]")
                    entry = f["entries"][entry_name]
                    for key in ("genomes", "contigs", "bins", "pixels", "indexes"):
                        if key in entry:
                            _build_tree(key, entry[key], entry_node)
        elif is_metacooler(file_path):
            # Metacool file: show core tables in fixed order.
            # chroms is a shim (soft link to contigs) and is omitted.
            for key in ("genomes", "contigs", "bins", "pixels", "indexes"):
                if key in f:
                    _build_tree(key, f[key], tree)
        else:
            # Plain cooler or other HDF5: show all top-level groups.
            for key in f:
                _build_tree(key, f[key], tree)

        console.print(tree)


def _convert_attr(val: object) -> object:
    """Convert HDF5 attribute values to YAML-friendly Python types."""
    import numpy as np

    if isinstance(val, np.integer):
        return int(val)
    if isinstance(val, np.floating):
        return float(val)
    if isinstance(val, bytes):
        val = val.decode()
    if isinstance(val, str):
        if val == "null":
            return None
        if val == "{}":
            return {}
        import json
        from datetime import datetime

        try:
            return json.loads(val)
        except ValueError:
            pass
        try:
            return datetime.fromisoformat(val)
        except ValueError:
            pass
    return val


def _collect_attrs_tree(obj: h5py.HLObject) -> dict:
    """Recursively build a nested dict of HDF5 attrs, matching cooler attrs format."""
    import h5py as _h5py

    result: dict = {}
    result["@attrs"] = {k: _convert_attr(v) for k, v in obj.attrs.items()}
    if isinstance(obj, _h5py.Group):
        for key in obj:
            try:
                child = obj[key]
                result[key] = _collect_attrs_tree(child)
            except Exception:
                # Skip broken soft links or inaccessible objects
                result[key] = {"@error": "inaccessible"}
    return result


@cli.command(
    name="attrs", help="Display HDF5 attributes (YAML, same format as cooler attrs)."
)
@click.argument("metacool_path", type=MetaCoolURI())
@click.argument("group_path", type=str, default="/")
@click.option(
    "-v",
    "--verbose",
    is_flag=True,
    help="Increase verbosity (debug logging).",
)
def cmd_attrs(metacool_path: str, group_path: str, verbose: bool) -> None:
    """Dump HDF5 attributes as YAML, matching cooler attrs output format.

    \b
    GROUP_PATH    HDF5 group path (default: /)
    """
    import h5py

    from metacooler.cli.logging_utils import setup_logging
    from metacooler.schema import is_mmetacooler
    from metacooler.uri import parse_uri

    setup_logging(verbose, command_name="metacooler attrs")

    file_path, uri_group = parse_uri(metacool_path)
    # Merge URI group path with explicit group_path argument
    resolved_group = uri_group if group_path == "/" else group_path

    with h5py.File(file_path, "r") as f:
        if is_mmetacooler(file_path) and resolved_group == "/":
            # Show attrs for ALL contained metacoolers
            all_data = {}
            all_data["@attrs"] = {k: _convert_attr(v) for k, v in f.attrs.items()}
            if "entries" in f:
                entries_data = {}
                for entry_name in f["entries"]:
                    entry = f["entries"][entry_name]
                    entries_data[entry_name] = _collect_attrs_tree(entry)
                all_data["entries"] = entries_data
            click.echo(
                yaml.dump(all_data, default_flow_style=False, allow_unicode=True),
                nl=False,
            )
        else:
            grp = f[resolved_group]
            data = _collect_attrs_tree(grp)
            click.echo(
                yaml.dump(data, default_flow_style=False, allow_unicode=True),
                nl=False,
            )
