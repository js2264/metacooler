"""metacooler info command - Display metadata and statistics."""

from __future__ import annotations

import json
from pathlib import Path

import rich_click as click
from rich.console import Console
from rich.table import Table

from metacooler.cli.main import MetaCoolURI, cli

# Exact order for JSON output as requested
_INFO_KEY_ORDER = [
    "bin-size",
    "bin-type",
    "creation-date",
    "format",
    "format-url",
    "format-version",
    "metacooler-format-version",
    "generated-by",
    "genome-assembly",
    "nbins",
    "ncontigs",
    "ngenomes",
    "nnz",
    "storage-mode",
    "sum",
    "ordering",
]


@cli.command(name="info", help="Display metadata and statistics.")
@click.argument("metacool_path", type=MetaCoolURI())
@click.option(
    "--table",
    "table_out",
    is_flag=True,
    help="Output as a rich table instead of JSON.",
)
@click.option(
    "-v",
    "--verbose",
    is_flag=True,
    help="Increase verbosity (debug logging).",
)
def cmd_info(metacool_path: str, table_out: bool, verbose: bool) -> None:
    """Display metadata and statistics for a metacool file."""
    import cooler
    import h5py
    from cooler.fileops import is_cooler, is_multires_file

    from metacooler.api import MetaCooler
    from metacooler.cli.logging_utils import setup_logging
    from metacooler.schema import is_metacooler, is_mmetacooler, list_metacoolers
    from metacooler.uri import parse_uri

    setup_logging(verbose, command_name="metacooler info")

    raw = metacool_path
    file_path, group_path = parse_uri(raw)

    # Check if this is an mmetacool without a group path
    if is_mmetacooler(file_path) and "::" not in raw:
        entries = list_metacoolers(file_path)
        entry_uris = [f"{file_path}::{e}" for e in entries]
        raise click.ClickException(
            f"This is an mmetacool file with {len(entries)} entries. "
            f"Specify an entry with URI syntax:\n"
            + "\n".join(f"  metacooler info {u}" for u in entry_uris)
        )

    # Check if this is an mcool without a resolution path
    if is_multires_file(str(file_path)) and group_path == "/":
        with h5py.File(file_path, "r") as f:
            resolutions = list(f["resolutions"])
        raise click.ClickException(
            f"This is a multi-resolution cooler with resolutions: {resolutions}. "
            f"Specify a resolution with URI syntax:\n"
            + "\n".join(
                f"  metacooler info {file_path}::resolutions/{r}" for r in resolutions
            )
        )

    # Plain cooler (or mcool with resolution URI): fall back to cooler.Cooler
    if not is_metacooler(file_path) and not ("::" in raw and is_mmetacooler(file_path)):
        cooler_uri = str(file_path) if group_path == "/" else raw
        if not is_cooler(cooler_uri):
            raise click.ClickException(
                f"Not a recognised metacooler or cooler file: {file_path}"
            )
        clr = cooler.Cooler(cooler_uri)
        click.echo(json.dumps(dict(clr.info), indent=2, default=str))
        return

    mc = MetaCooler(raw)
    info = mc.info

    # Build ordered dict
    ordered_info = {}
    for key in _INFO_KEY_ORDER:
        if key in info:
            ordered_info[key] = info[key]

    if table_out:
        table = Table(
            title=f"MetaCooler Info: {Path(metacool_path.split('::')[0]).name}"
        )
        table.add_column("Property", style="cyan")
        table.add_column("Value", style="magenta")

        table.add_row("Format", str(ordered_info.get("format", "N/A")))
        table.add_row("Format URL", str(ordered_info.get("format-url", "N/A")))
        table.add_row("Format version", str(ordered_info.get("format-version", "N/A")))
        table.add_row("Generated by", str(ordered_info.get("generated-by", "N/A")))
        table.add_row("Assembly", str(ordered_info.get("genome-assembly", "N/A")))
        table.add_row("Ordering", str(ordered_info.get("ordering", "N/A")))
        table.add_row("Genomes", str(ordered_info.get("ngenomes", "N/A")))
        table.add_row("Contigs", str(ordered_info.get("ncontigs", "N/A")))
        table.add_row("Bins", str(ordered_info.get("nbins", "N/A")))
        table.add_row("Pixels (NNZ)", str(ordered_info.get("nnz", "N/A")))
        table.add_row("Sum", str(ordered_info.get("sum", "N/A")))
        table.add_row("Bin size", str(ordered_info.get("bin-size", "N/A")))
        table.add_row("Bin type", str(ordered_info.get("bin-type", "N/A")))

        console = Console()
        console.print(table)
        return

    click.echo(json.dumps(ordered_info, indent=2, default=str))
